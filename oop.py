class TemperatureSensor:

    def __init__(self, sensor_name, temperature):
        self.sensor_name =   sensor_name
        self.temperature = temperature

    def check_temperature(self):

        if self.temperature > 80:
            return "High Temperature"

        elif self.temperature < 20:
            return "Low Temperature"

        else:
            return "Normal Temperature"

    def show_status(self):

        print("Sensor Name :", self.sensor_name)
        print("Temperature  :", self.temperature, "°C")
        print("Status       :", self.check_temperature())


print("========== Industrial Temperature Monitoring ==========\n")

temperature = float(input("Enter current temperature (°C): "))

sensor = TemperatureSensor("RTD-01", temperature)

print("\n========== Sensor Status ==========\n")

sensor.show_status()

