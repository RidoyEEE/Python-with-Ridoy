print("========== Motor Overload Protection ==========")

Assistent_engineer = "Engr. Ridoy Chandra Shill"
motor_name = "Conveyor Belt Drive Motor"

rated_current = float(input("Enter the rated current (A): "))
measured_current = float(input("Enter the measured current (A): "))

print("\nInspection Report")
print("-" * 45)

print(f"Assistent Engineer : {Assistent_engineer}")
print(f"Motor Name          : {motor_name}")
print(f"Rated Current       : {rated_current:.2f} A")
print(f"Measured Current    : {measured_current:.2f} A")

print("\nInspection Result")
print("-" * 45)

if measured_current <= rated_current:
    print("Status         : Normal Operation")
    print("Condition      : Motor is operating within the rated current.")
    print(f"Verified By    : {Assistent_engineer}")
    print("Recommendation : Continue normal operation.")

elif measured_current <= rated_current * 1.10:
    print("Status         : Light Overload")
    print("Condition      : Current is slightly above the rated value.")
    print(f"Notify         : {Assistent_engineer}")
    print("Recommendation : Monitor the motor and reduce the mechanical load.")

elif measured_current <= rated_current * 1.20:
    print("Status         : High Overload")
    print("Condition      : Motor may overheat if operated continuously.")
    print(f"Notify         : {Assistent_engineer}")
    print("Recommendation : Stop the motor and inspect the drive system.")

else:
    print("Status        : Critical Overload")
    print("Condition      : Current exceeds 120% of the rated value.")
    print(f"Notify         : {Assistent_engineer} immediately.")
    print("Recommendation : Shut down the motor immediately and inspect the protection system.")

print("\nInspection completed.")

