print("========== Supply Voltage Monitoring ==========")

Assistent_engineer = "Engr. Ridoy Chandra Shill"

nominal_voltage = 230      # V (Bangladesh Standard)
measured_voltage = float(input("Enter the measured supply voltage (V): "))

print("\nVoltage Inspection Report")
print("-" * 45)

print(f"Assistent Engineer : {Assistent_engineer}")
print(f"Nominal Voltage     : {nominal_voltage} V")
print(f"Measured Voltage    : {measured_voltage:.1f} V")

print("\nInspection Result")
print("-" * 45)

if measured_voltage < 210:
    print("Status         : Low Voltage")
    print("Risk           : Equipment may not operate properly.")
    print(f"Notify         : {Assistent_engineer}")
    print("Recommendation : Inspect the power supply and feeder line.")

elif measured_voltage <= 240:
    print("Status         : Normal Voltage")
    print("Condition      : Supply voltage is within the acceptable range.")
    print(f"Verified By    : {Assistent_engineer}")
    print("Recommendation : Continue normal operation.")

else:
    print("Status         : High Voltage")
    print("Risk           : Equipment insulation may be stressed.")
    print(f"Notify         : {Assistent_engineer}")
    print("Recommendation : Check the transformer tap setting and supply system.")

print("\nVoltage inspection completed successfully.")
