# Example 01 : Solar Energy Data Logger
# ============================================================

solar_energy = []

print("Solar Energy Data Logger")
print("-" * 40)

# Store solar energy data for 7 days
for day in range(1, 8):

    energy = float(input(f"Day {day} Energy (kWh): "))
    solar_energy.append(energy)

print("\nDaily Energy Generation")

for day, energy in enumerate(solar_energy, start=1):
    print(f"Day {day} : {energy} kWh")

print("\nWeekly Summary")

print(f"Total Energy   : {sum(solar_energy):.2f} kWh")
print(f"Average Energy : {sum(solar_energy)/len(solar_energy):.2f} kWh")
print(f"Highest Energy : {max(solar_energy):.2f} kWh")
print(f"Lowest Energy  : {min(solar_energy):.2f} kWh")

