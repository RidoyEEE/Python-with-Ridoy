# Topic      : Sets
# Example 01 : PLC Digital Input Status
# ============================================================

print("========== PLC Digital Input Status ==========\n")

active_inputs = set()

number_of_inputs = int(input("How many active PLC inputs? "))

print()

for i in range(number_of_inputs):

    plc_input = input(f"Enter Active Input {i + 1}: ").upper()

    active_inputs.add(plc_input)

print("\n========== Active PLC Inputs ==========\n")

for input_signal in sorted(active_inputs):

    if input_signal == "X0":
        print("X0 → Start Push Button")

    elif input_signal == "X1":
        print("X1 → Stop Push Button")

    elif input_signal == "X2":
        print("X2 → Emergency Stop")

    elif input_signal == "X3":
        print("X3 → Photoelectric Sensor")

    elif input_signal == "X4":
        print("X4 → Limit Switch")

    elif input_signal == "X5":
        print("X5 → Proximity Sensor")

    else:
        print(f"{input_signal} → Unknown Input")

print(f"\nTotal Active Inputs : {len(active_inputs)}")

