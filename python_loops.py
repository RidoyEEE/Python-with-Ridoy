# Example 02 : Traffic Signal Controllering
# ============================================================

print("========== Traffic Signal Controllering ==========")

cycle = 1

while True:

    print("\n" + "=" * 45)
    print(f"Traffic Signal Cycle : {cycle}")
    print("=" * 45)

    print("\nState 1")
    print("Road-A Signal : GREEN")
    print("Road-B Signal : RED")
    print("Status        : Vehicles on Road-A can move.")

    print("\nState 2")
    print("Road-A Signal : YELLOW")
    print("Road-B Signal : RED")
    print("Status        : Road-A should prepare to stop.")

    print("\nState 3")
    print("Road-A Signal : RED")
    print("Road-B Signal : GREEN")
    print("Status        : Vehicles on Road-B can move.")

    print("\nState 4")
    print("Road-A Signal : RED")
    print("Road-B Signal : YELLOW")
    print("Status        : Road-B should prepare to stop.")

    print("\nCycle Completed.")

    cycle += 1