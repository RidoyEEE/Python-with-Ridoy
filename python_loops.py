print("========== Conveyor Fruit Sorting System ==========")

# Fruits detected on the conveyor
detected_items = [
    "Orange",
    "Mango",
    "Apple",
    "Banana"
]

orange_count = 0
mango_count = 0
apple_count = 0
banana_count = 0

box_number = 1

print("\nConveyor Status : RUNNING")
print("-" * 55)

for item in detected_items:

    print(f"\nBox {box_number}")
    print(f"Detected Item : {item}")

    if item == "Orange":

        print("\nSensor Status")
        print("Sensor-1 :   ON")
        print("Sensor-2 : OFF")
        print("Sensor-3 : OFF")
        print("Sensor-4 : OFF")

        print("\nPLC Command : Move box to Lane-A")
        print("Sorting Status  : Completed")

        orange_count += 1

    elif item == "Mango":

        print("\nSensor Status")
        print("Sensor-1 : OFF")
        print("Sensor-2 :   ON")
        print("Sensor-3 : OFF")
        print("Sensor-4 : OFF")

        print("\nPLC Command : Move box to Lane-B")
        print("Sorting Status : Completed")

        mango_count += 1

    elif item == "Apple":

        print("\nSensor Status")
        print("Sensor-1 : OFF")
        print("Sensor-2 : OFF")
        print("Sensor-3 :   ON")
        print("Sensor-4 : OFF")

        print("\nPLC Command : Move box to Lane-C")
        print("Sorting Status : Completed")

        apple_count += 1

    else:

        print("\nSensor Status")
        print("Sensor-1 : OFF")
        print("Sensor-2 : OFF")
        print("Sensor-3 : OFF")
        print("Sensor-4 :   ON")

        print("\nPLC Command : Move box to Lane-D")
        print("Sorting Status : Completed")

        banana_count += 1

    box_number += 1

print("Production Summary")
print("=" * 45)

print(f"Total Boxes Sorted : {len(detected_items)}")
print(f"Orange Boxes  : {orange_count}")
print(f"Mango Boxes    : {mango_count}")
print(f"Apple Boxes       : {apple_count}")
print(f"Banana Boxes   : {banana_count}")

print("\nSystem Status")
print("Conveyor : STOPPED")
print("PLC       : READY FOR NEXT BATCH")
print("=" * 55)

# ============================================================
