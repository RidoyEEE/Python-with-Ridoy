# Practice Program 02: Python for Electrical Engineering
# Topic      : Functions
# Example 02 : Solar Charge Time Estimator
# Mathematical Background
# Step 1:
# Calculate the stored energy of the battery.
# Battery Energy (Wh) = Battery Voltage (V) × Battery Capacity (Ah)

# Step 2:
# Estimate the battery charging time using the available solar power.
# Charging Time (Hours) = Battery Energy (Wh) / Solar Charging Power (W)
# ============================================================


# Calculate battery energy
def battery_energy(voltage, capacity):

    energy = voltage * capacity

    return energy


# Estimate charging time
def charging_time(energy, solar_power):

    time = energy / solar_power

    return time


print(" ======= Solar Charge Time Estimator ====== ")

battery_voltage = float(input("Enter battery voltage (V): "))
battery_capacity = float(input("Enter battery capacity (Ah): "))
solar_power = float(input("Enter solar charging power (W): "))

energy = battery_energy(battery_voltage, battery_capacity)

time = charging_time(energy, solar_power)

print("\n ======= Charging Report ========= ")
print(f"Battery Energy  : {energy:.2f} Wh")
print(f"Solar Charging Power  : {solar_power:.2f} W")
print(f"Estimated Charge Time  : {time:.2f} Hours")

if time <= 4:
    print("Charging Status        : Fast Charging")

elif time <= 8:
    print("Charging Status        : Normal Charging")

else:
    print("Charging Status        : Slow Charging")