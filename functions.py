# Mathematical Background

# Step 1:
# Calculate the total installed solar capacity.
# Total Capacity (W) = Number of Panels × Power per Panel (W)

# Step 2:
# Estimate the daily energy generation.
# Daily Energy (kWh) = (Total Capacity (W) × Sunlight Hours) / 1000
# ============================================================


# Display solar panel information
def show_panel_information():

    print("\n========== Solar Panel Information ==========")
    print("Number of Panels :", number_of_panels)
    print("Power per Panel  :", panel_power, "W")
    print("Sunlight Hours   :", sunlight_hours, "Hours")


# Calculate total solar capacity
def calculate_total_capacity():

    total_capacity = number_of_panels * panel_power
    return total_capacity


# Calculate daily energy generation
def calculate_daily_energy(total_capacity):

    daily_energy = (total_capacity * sunlight_hours) / 1000
    return daily_energy


# Display final report
def show_report(total_capacity, daily_energy):

    print("\n========== Solar Energy Report ==========")
    print(f"Total Capacity : {total_capacity} W")
    print(f"Daily Energy   : {daily_energy:.2f} kWh")


# ---------------- Main Program ----------------

number_of_panels = int(input("Enter number of solar panels : "))
panel_power = float(input("Enter power of one panel (W) : "))
sunlight_hours = float(input("Enter average sunlight hours : "))

show_panel_information()

total_capacity = calculate_total_capacity()
daily_energy = calculate_daily_energy(total_capacity)

show_report(total_capacity, daily_energy)

